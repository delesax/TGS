-- ---------------------------------------------------------------------------
-- Admin: approve (issue invites)
-- ---------------------------------------------------------------------------
-- p_items: up to 50 of { "request_id": uuid } (a request from the form) or { "email": text } (an address pasted in by an
-- admin), each with "code_hash" and, when emailing, "code". The app makes the codes; the database never sees one unless an
-- email is to be sent. A key makes the whole call safe to repeat. Returns one result per item (no codes).
create or replace function public.issue_invites(p_items jsonb, p_send_email boolean, p_key uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  s public.community_settings%rowtype;
  n integer;
  item jsonb;
  k integer := 0;
  v_email text;
  v_req public.join_requests%rowtype;
  v_hash text;
  v_code text;
  times timestamptz[];
  v_inv uuid;
  v_send timestamptz;
  v_exp timestamptz;
  v_status text;
  results jsonb := '[]'::jsonb;
  issued integer := 0;
begin
  if not public.is_admin() then
    raise exception 'NOT_ADMIN: only admins can issue invites' using errcode = '42501';
  end if;
  if p_items is null or jsonb_typeof(p_items) <> 'array' or p_key is null then
    raise exception 'BAD_INPUT: send a list of people and a key' using errcode = '22023';
  end if;
  n := jsonb_array_length(p_items);
  if n < 1 or n > 50 then
    raise exception 'BATCH_SIZE: choose 1 to 50 people at a time' using errcode = '22023';
  end if;

  insert into public.invite_batch_keys (key, created_by) values (p_key, uid) on conflict do nothing;
  if not found then
    return jsonb_build_object('duplicate', true, 'results', '[]'::jsonb);
  end if;

  select * into s from public.community_settings;
  if coalesce(p_send_email, false) and s.email_essentials_only and not ('invite' = any (s.email_essential_kinds)) then
    raise exception 'INVITE_EMAIL_OFF: add invite to the essential email kinds before emailing invites' using errcode = '42501';
  end if;
  if coalesce(p_send_email, false) then
    times := public.invite_send_times(n);
  end if;

  for item in select * from jsonb_array_elements(p_items) loop
    v_hash := item ->> 'code_hash';
    v_code := nullif(item ->> 'code', '');
    if v_hash is null or v_hash !~ '^[0-9a-f]{64}$' then
      raise exception 'BAD_INPUT: every person needs a code hash' using errcode = '22023';
    end if;
    if coalesce(p_send_email, false) and v_code is null then
      raise exception 'BAD_INPUT: emailing an invite needs its code' using errcode = '22023';
    end if;

    v_status := null;
    v_req := null;
    if nullif(item ->> 'request_id', '') is not null then
      select * into v_req from public.join_requests where id = (item ->> 'request_id')::uuid for update;
      if not found then
        v_status := 'not_found';
      elsif v_req.status <> 'pending' then
        v_status := 'not_pending';
      elsif exists (select 1 from auth.users u where lower(u.email) = v_req.email) then
        v_status := 'already_member';
      end if;
      v_email := v_req.email;
    else
      v_email := lower(btrim(coalesce(item ->> 'email', '')));
      if char_length(v_email) > 320 or v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
        v_status := 'bad_email';
      elsif exists (select 1 from auth.users u where lower(u.email) = v_email) then
        v_status := 'already_member';
      else
        select * into v_req from public.join_requests where email = v_email and status in ('pending', 'approved') for update;
        if found and v_req.status = 'approved' then
          v_status := 'already_invited';
        elsif not found then
          insert into public.join_requests (email, source) values (v_email, 'admin') returning * into v_req;
        end if;
      end if;
    end if;

    if v_status is null then
      k := k + 1;
      v_send := case when coalesce(p_send_email, false) then times[k] else now() end;
      v_exp := v_send + make_interval(days => s.invite_expiry_days);
      insert into public.invites (code_hash, max_uses, invited_email, expires_at, note, created_by, join_request_id)
      values (v_hash, 1, v_req.email, v_exp, 'Join request', uid, v_req.id)
      returning id into v_inv;
      update public.join_requests
      set status = 'approved', decided_at = now(), decided_by = uid, invite_id = v_inv, approval_key = p_key
      where id = v_req.id;
      if coalesce(p_send_email, false) then
        perform public.enqueue_invite_email(v_req.email, jsonb_build_object('invite_id', v_inv, 'code', v_code, 'expires_at', v_exp), 'invite:' || v_inv, v_send);
      end if;
      insert into public.audit_log (actor_id, action, target_table, target_id, details)
      values (uid, 'invite.issued', 'invites', v_inv::text,
              jsonb_build_object('request_id', v_req.id, 'emailed', coalesce(p_send_email, false), 'source', v_req.source));
      issued := issued + 1;
      v_status := 'issued';
    end if;

    results := results || jsonb_build_array(jsonb_build_object(
      'request_id', v_req.id, 'email', v_email, 'status', v_status, 'invite_id', v_inv,
      'send_after', case when v_status = 'issued' and coalesce(p_send_email, false) then v_send end,
      'expires_at', case when v_status = 'issued' then v_exp end));
    v_inv := null;
  end loop;

  insert into public.audit_log (actor_id, action, target_table, target_id, details)
  values (uid, 'invite.batch_issued', 'invites', null, jsonb_build_object('count', issued, 'asked', n, 'emailed', coalesce(p_send_email, false), 'key', p_key));

  return jsonb_build_object('duplicate', false, 'results', results);
end;
$$;

revoke execute on function public.issue_invites(jsonb, boolean, uuid) from public, anon;
grant execute on function public.issue_invites(jsonb, boolean, uuid) to authenticated;

