-- Admin-generated, email-bound invite codes and a public "request to join" form.
--
-- Additive and backward compatible with the code on main (deploy order: this migration first, then the code):
--   * invites gain code_hash (the SHA-256 of the code, hex) and join_request_id; code becomes nullable so a new
--     invite can be stored hashed only. Existing invites keep their plaintext code and keep working: the sign-up
--     functions now match either the plaintext code or the hash of what was typed.
--   * join_requests: people who asked to join (from the public form) or whom an admin added by hand. Admin read
--     only; every write goes through the functions below.
--   * email_outbox can hold an email for an address that has no account yet (user_id nullable, to_email, kind
--     'invite'). The deployed email processor never sees such a row, because none exists until the new admin
--     screen is deployed.
--   * Admin functions: issue_invites, reject_join_requests, revoke_invite, reissue_invite, admin_invites_overview,
--     invite_email_budget. Public (service role only): request_to_join. Housekeeping: purge_join_requests.
--   * Codes are generated by the app (never by the database) and only their hash is stored. An invite email needs the
--     code, so the code sits in the email's queue row (a table nobody but the service role can read) until the
--     email is sent, and the processor then clears it.
-- Nothing here stores or logs an email address in audit_log: audit rows carry ids and counts only.

-- ---------------------------------------------------------------------------
-- The hash used for lookups
-- ---------------------------------------------------------------------------
create or replace function public.invite_code_hash(p_code text)
returns text
language sql
immutable
set search_path = ''
as $$
  select encode(sha256(convert_to(upper(btrim(coalesce(p_code, ''))), 'UTF8')), 'hex');
$$;

revoke execute on function public.invite_code_hash(text) from public, anon, authenticated;

