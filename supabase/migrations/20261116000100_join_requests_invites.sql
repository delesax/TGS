-- Admin: the list of decided requests with their invite and email state (no codes)
-- ---------------------------------------------------------------------------
create or replace function public.admin_invites_overview()
returns table (
  request_id uuid, email text, status text, source text, created_at timestamptz, decided_at timestamptz,
  invite_id uuid, expires_at timestamptz, revoked_at timestamptz, used boolean, email_state text, send_after timestamptz
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'NOT_ADMIN: only admins can read invites' using errcode = '42501';
  end if;
  return query
  select r.id, r.email, r.status, r.source, r.created_at, r.decided_at,
         i.id, i.expires_at, i.revoked_at, coalesce(i.use_count > 0, false),
         (select o.status from public.email_outbox o where o.kind = 'invite' and o.payload ->> 'invite_id' = i.id::text order by o.id desc limit 1),
         (select o.send_after from public.email_outbox o where o.kind = 'invite' and o.payload ->> 'invite_id' = i.id::text order by o.id desc limit 1)
  from public.join_requests r
  left join public.invites i on i.id = r.invite_id
  where r.status <> 'pending'
  order by coalesce(r.decided_at, r.created_at) desc
  limit 300;
