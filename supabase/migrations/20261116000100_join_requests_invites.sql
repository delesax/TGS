-- ---------------------------------------------------------------------------
-- Public: ask to join (service role only; the app applies its rate limits first)
-- ---------------------------------------------------------------------------
-- Always does the same checks and never says whether the address is a member or has already asked: a person who is
-- already a member, already asked, was rejected within the last 30 days, or asks while the queue is full gets the same
-- result as everyone else, and nothing is saved.
create or replace function public.request_to_join(p_email text, p_note text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := lower(btrim(coalesce(p_email, '')));
  v_note text := nullif(btrim(regexp_replace(coalesce(p_note, ''), '[[:cntrl:]]', ' ', 'g')), '');
  is_member boolean;
  has_request boolean;
  backlog integer;
begin
  if char_length(v_email) > 320 or v_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    raise exception 'BAD_EMAIL: enter an email address' using errcode = '22023';
  end if;
  if v_note is not null then
    v_note := left(v_note, 200);
  end if;
  select exists (select 1 from auth.users u where lower(u.email) = v_email) into is_member;
  select exists (select 1 from public.join_requests r where r.email = v_email and r.status in ('pending', 'approved', 'rejected')) into has_request;
  select count(*) into backlog from public.join_requests where status = 'pending';
  if is_member or has_request or backlog >= 500 then
    return;
  end if;
  insert into public.join_requests (email, note, source) values (v_email, v_note, 'form') on conflict do nothing;
end;
$$;

revoke execute on function public.request_to_join(text, text) from public, anon, authenticated;
grant execute on function public.request_to_join(text, text) to service_role;

-- ---------------------------------------------------------------------------
-- Housekeeping: 30 days
-- ---------------------------------------------------------------------------
-- Pending requests older than 30 days expire. Approved ones whose invite was used become "joined", or "expired" when the
-- unused invite has expired. Rejected, revoked, expired and joined requests are deleted 30 days after the decision.
create or replace function public.purge_join_requests()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  n integer;
begin
  update public.join_requests set status = 'expired', decided_at = now()
  where status = 'pending' and created_at < now() - interval '30 days';
  update public.join_requests r set status = 'joined', decided_at = now()
  from public.invites i
  where r.status = 'approved' and i.id = r.invite_id and i.use_count > 0;
  update public.join_requests r set status = 'expired', decided_at = now()
  from public.invites i
  where r.status = 'approved' and i.id = r.invite_id and i.use_count = 0 and i.expires_at is not null and i.expires_at < now();
  delete from public.join_requests
  where status in ('rejected', 'revoked', 'expired', 'joined') and decided_at < now() - interval '30 days';
  get diagnostics n = row_count;
  delete from public.invite_batch_keys where created_at < now() - interval '30 days';
  perform public.retention_log('join-requests-purge', n);
  return n;
end;
$$;

revoke execute on function public.purge_join_requests() from public, anon, authenticated;

select cron.schedule('join-requests-purge', '31 3 * * *', 'select public.purge_join_requests()');
