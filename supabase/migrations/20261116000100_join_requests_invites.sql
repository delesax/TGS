create or replace function public.invite_email_budget()
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  s public.community_settings%rowtype;
  today date := public.uk_today();
  day_start timestamptz := today::timestamp at time zone 'Europe/London';
  next_start timestamptz := (today + 1)::timestamp at time zone 'Europe/London';
  used integer;
  inv_used integer;
  inv_queued integer;
  auth_today integer;
begin
  if not public.is_admin() then
    raise exception 'NOT_ADMIN: only admins can see the email budget' using errcode = '42501';
  end if;
  select * into s from public.community_settings;
  select count(*) into used from public.email_outbox
    where (status = 'sent' and sent_at >= day_start) or (status = 'sending' and locked_at >= day_start);
  select count(*) into inv_used from public.email_outbox
    where kind = 'invite' and ((status = 'sent' and sent_at >= day_start) or (status = 'sending' and locked_at >= day_start));
  select count(*) into inv_queued from public.email_outbox
    where kind = 'invite' and status = 'queued' and send_after < next_start;
  select count(*) into auth_today from auth.users where created_at >= day_start;
  return jsonb_build_object(
    'app_cap', s.email_global_daily_cap, 'app_sent_today', used,
    'invite_limit', s.invite_daily_email_limit, 'invite_sent_today', inv_used, 'invite_waiting_today', inv_queued,
    'provider_limit', s.resend_daily_limit, 'auth_emails_estimate', auth_today,
    'room_today', greatest(0, least(s.email_global_daily_cap - used, s.invite_daily_email_limit - inv_used - inv_queued, s.resend_daily_limit - used - auth_today)),
    'invite_waiting_total', (select count(*) from public.email_outbox where kind = 'invite' and status = 'queued'),
    'expiry_days', s.invite_expiry_days
  );
end;
$$;

