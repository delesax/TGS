create or replace function public.revoke_invite(p_invite_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  i public.invites%rowtype;
begin
  if not public.is_admin() then
    raise exception 'NOT_ADMIN: only admins can revoke invites' using errcode = '42501';
  end if;
  select * into i from public.invites where id = p_invite_id for update;
  if not found then
    raise exception 'NOT_FOUND: no such invite' using errcode = 'P0002';
  end if;
  if i.revoked_at is not null then
    return;
  end if;
  if i.use_count > 0 then
    raise exception 'ALREADY_USED: this invite has been used and cannot be revoked' using errcode = '42501';
  end if;
  update public.invites set revoked_at = now() where id = i.id;
  update public.join_requests set status = 'revoked', decided_at = now(), decided_by = uid where invite_id = i.id and status = 'approved';
  -- An invite email still waiting is dropped (and its code cleared).
  update public.email_outbox set status = 'skipped', last_error = 'invite revoked', payload = '{}'::jsonb
  where kind = 'invite' and status = 'queued' and payload ->> 'invite_id' = i.id::text;
  insert into public.audit_log (actor_id, action, target_table, target_id, details)
  values (uid, 'invite.revoked', 'invites', i.id::text, jsonb_build_object('request_id', i.join_request_id));
end;
$$;

