-- Revokes the old invite and issues a fresh one for the same address. Safe to repeat with the same key.
create or replace function public.reissue_invite(p_invite_id uuid, p_code_hash text, p_code text, p_send_email boolean, p_key uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid uuid := auth.uid();
  s public.community_settings%rowtype;
  old public.invites%rowtype;
  v_inv uuid;
  v_send timestamptz;
  v_exp timestamptz;
begin
  if not public.is_admin() then
    raise exception 'NOT_ADMIN: only admins can re-issue invites' using errcode = '42501';
  end if;
  if p_key is null or p_code_hash is null or p_code_hash !~ '^[0-9a-f]{64}$' then
    raise exception 'BAD_INPUT: send a code hash and a key' using errcode = '22023';
  end if;
  if coalesce(p_send_email, false) and nullif(p_code, '') is null then
    raise exception 'BAD_INPUT: emailing an invite needs its code' using errcode = '22023';
  end if;
  insert into public.invite_batch_keys (key, created_by) values (p_key, uid) on conflict do nothing;
  if not found then
    return jsonb_build_object('duplicate', true);
  end if;
  select * into old from public.invites where id = p_invite_id for update;
  if not found or old.invited_email is null then
    raise exception 'NOT_FOUND: only an invite made for one email address can be re-issued' using errcode = 'P0002';
  end if;
  if old.use_count > 0 then
    raise exception 'ALREADY_USED: this invite has been used' using errcode = '42501';
  end if;
  if exists (select 1 from auth.users u where lower(u.email) = old.invited_email) then
    raise exception 'ALREADY_MEMBER: that address already has an account' using errcode = '42501';
  end if;
  select * into s from public.community_settings;
  if coalesce(p_send_email, false) and s.email_essentials_only and not ('invite' = any (s.email_essential_kinds)) then
    raise exception 'INVITE_EMAIL_OFF: add invite to the essential email kinds before emailing invites' using errcode = '42501';
  end if;

  if old.revoked_at is null then
    update public.invites set revoked_at = now() where id = old.id;
  end if;
  update public.email_outbox set status = 'skipped', last_error = 'invite re-issued', payload = '{}'::jsonb
  where kind = 'invite' and status = 'queued' and payload ->> 'invite_id' = old.id::text;

  v_send := case when coalesce(p_send_email, false) then (public.invite_send_times(1))[1] else now() end;
  v_exp := v_send + make_interval(days => s.invite_expiry_days);
  insert into public.invites (code_hash, max_uses, invited_email, expires_at, note, created_by, join_request_id)
  values (p_code_hash, 1, old.invited_email, v_exp, 'Join request', uid, old.join_request_id)
  returning id into v_inv;
  update public.join_requests
  set status = 'approved', decided_at = now(), decided_by = uid, invite_id = v_inv, approval_key = p_key
  where id = old.join_request_id;
  if coalesce(p_send_email, false) then
    perform public.enqueue_invite_email(old.invited_email, jsonb_build_object('invite_id', v_inv, 'code', p_code, 'expires_at', v_exp), 'invite:' || v_inv, v_send);
  end if;
  insert into public.audit_log (actor_id, action, target_table, target_id, details)
  values (uid, 'invite.reissued', 'invites', v_inv::text,
          jsonb_build_object('replaces', old.id, 'request_id', old.join_request_id, 'emailed', coalesce(p_send_email, false)));
  return jsonb_build_object('duplicate', false, 'invite_id', v_inv, 'email', old.invited_email,
    'send_after', case when coalesce(p_send_email, false) then v_send end, 'expires_at', v_exp);
end;
$$;

revoke execute on function public.reissue_invite(uuid, text, text, boolean, uuid) from public, anon;
grant execute on function public.reissue_invite(uuid, text, text, boolean, uuid) to authenticated;

