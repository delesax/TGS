-- ---------------------------------------------------------------------------
-- When may each invite email go? (the budget)
-- ---------------------------------------------------------------------------
-- Today's room is the smallest of: what is left of the app's daily cap, what is left of the invite limit, and what is
-- left of the provider's daily limit after the app's mail and an estimate of Supabase's own sign-up emails (one for
-- each account created today). Invites beyond that wait for the next UK days, in order, at five past midnight.
create or replace function public.invite_send_times(p_count integer)
returns timestamptz[]
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  s public.community_settings%rowtype;
  today date := public.uk_today();
  day_start timestamptz := today::timestamp at time zone 'Europe/London';
  next_start timestamptz := (today + 1)::timestamp at time zone 'Europe/London';
  used integer;
  inv_used integer;
  inv_queued integer;
  auth_today integer;
  room integer;
  per_day integer;
  v_out timestamptz[] := '{}';
  i integer;
begin
  select * into s from public.community_settings;
  select count(*) into used from public.email_outbox
    where (status = 'sent' and sent_at >= day_start) or (status = 'sending' and locked_at >= day_start);
  select count(*) into inv_used from public.email_outbox
    where kind = 'invite' and ((status = 'sent' and sent_at >= day_start) or (status = 'sending' and locked_at >= day_start));
  select count(*) into inv_queued from public.email_outbox
    where kind = 'invite' and status = 'queued' and send_after < next_start;
  select count(*) into auth_today from auth.users where created_at >= day_start;
  room := greatest(0, least(s.email_global_daily_cap - used, s.invite_daily_email_limit - inv_used - inv_queued, s.resend_daily_limit - used - auth_today));
  per_day := greatest(1, least(s.invite_daily_email_limit, s.email_global_daily_cap));
  for i in 0 .. greatest(p_count, 1) - 1 loop
    if i < room then
      v_out := v_out || now();
    else
      v_out := v_out || (((today + 1 + ((i - room) / per_day))::timestamp at time zone 'Europe/London') + interval '5 minutes');
    end if;
  end loop;
  return v_out;
end;
$$;

revoke execute on function public.invite_send_times(integer) from public, anon, authenticated;

