#!/usr/bin/env bash
# Writes .env.test.local from the running LOCAL Supabase (npx supabase start).
# Tests read this file, so they never touch the hosted project.
set -euo pipefail
cd "$(dirname "$0")/.."

status="$(npx --no-install supabase status -o env 2>/dev/null)"
get() { printf '%s\n' "$status" | sed -n "s/^$1=\"\{0,1\}\([^\"]*\)\"\{0,1\}$/\1/p" | head -1; }

api_url="$(get API_URL)"
anon_key="$(get PUBLISHABLE_KEY)"; [ -n "$anon_key" ] || anon_key="$(get ANON_KEY)"
service_key="$(get SECRET_KEY)"; [ -n "$service_key" ] || service_key="$(get SERVICE_ROLE_KEY)"
db_url="$(get DB_URL)"
mail_url="$(get MAILPIT_URL)"; [ -n "$mail_url" ] || mail_url="$(get INBUCKET_URL)"

if [ -z "$api_url" ] || [ -z "$anon_key" ] || [ -z "$service_key" ]; then
  echo "Local Supabase is not running. Start it with: npx supabase start" >&2
  exit 1
fi

umask 077
cat > .env.test.local <<EOF
# Generated by scripts/local-test-env.sh for LOCAL Supabase only. Not committed.
NEXT_PUBLIC_SITE_URL=http://localhost:3100
NEXT_PUBLIC_SUPABASE_URL=$api_url
NEXT_PUBLIC_SUPABASE_ANON_KEY=$anon_key
SUPABASE_SERVICE_ROLE_KEY=$service_key
DATABASE_URL=$db_url
MAILPIT_URL=${mail_url:-http://127.0.0.1:54324}
# Matches the dummy Vault secret in supabase/seed.sql. Local only.
EMAIL_PROCESSOR_SECRET=local-email-processor-secret
# Matches the dummy Vault secret in supabase/seed.sql. Local only.
MODERATION_PROCESSOR_SECRET=local-moderation-processor-secret
# The keyword-driven stand-in: tests never call the real AI API.
AI_PROVIDER=fake
EOF
echo "Wrote .env.test.local for local Supabase at $api_url"
